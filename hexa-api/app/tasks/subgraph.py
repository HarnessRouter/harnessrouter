"""Bounded static subgraphs owned by a parent NodeRun.

The child graph is copied into the Run snapshot and materialized once. It is
never generated by the model and cannot contain another control construct.
"""
import json
from datetime import datetime, timezone

from app.db.models import NodeRun
from app.tasks.dynamic_graph import graph_ready, graph_valid
from app.tasks.execution_binding import execution_binding


def _children(db, control):
    state = json.loads(control.input_json)
    ids = state.get('subgraph_node_run_ids', state.get('nested_subgraph_node_run_ids', []))
    rows = [db.get(NodeRun, identity) for identity in ids]
    if any(row is None or row.run_id != control.run_id or row.node_id != control.node_id
            or row.iteration != control.iteration or row.execution_kind != 'subgraph_node'
            or json.loads(row.input_json).get('subgraph_parent_node_run_id') != control.id
           for row in rows):
        raise ValueError('invalid persisted subgraph manifest')
    return rows


def _refs(rows, child_state):
    by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in rows}
    result = []
    for identity in child_state.get('inputRefs', []):
        row = by_id.get(identity)
        if row and row.status == 'succeeded' and row.output_json:
            result.append({'id': identity, 'node_run_id': row.id, 'output': json.loads(row.output_json)})
    return result


def _manifest_output(rows):
    return [{'id': json.loads(row.input_json)['subgraph_node_id'], 'status': row.status,
             **({'output': json.loads(row.output_json)} if row.output_json else {}),
             **({'error_code': row.error_code} if row.error_code else {})} for row in rows]


def _static_ready(rows, limit):
    """Select ready children; a running nested control occupies one local slot."""
    by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in rows}
    slots = max(0, limit - sum(row.status == 'running' for row in rows))
    return [row for row in rows if row.status == 'idle' and all(
        by_id[dep].status == 'succeeded'
        for dep in json.loads(row.input_json).get('deps', []))][:slots]


def _nested_children(db, control):
    state = json.loads(control.input_json)
    ids = state.get('nested_subgraph_node_run_ids', [])
    rows = [db.get(NodeRun, identity) for identity in ids]
    if any(row is None or row.run_id != control.run_id or row.node_id != control.node_id
            or row.iteration != control.iteration or row.execution_kind != 'subgraph_node'
            or json.loads(row.input_json).get('subgraph_parent_node_run_id') != control.id
           for row in rows):
        raise ValueError('invalid nested subgraph manifest')
    return rows


def retry_subgraph(db, run, item, control, selected_id, *, encoded, error):
    """Append a subgraph control attempt while preserving successful child history."""
    children = _children(db, control)
    all_children = list(children)
    for child in children:
        state = json.loads(child.input_json)
        if state.get('nested_subgraph_node_run_ids'):
            all_children.extend(_nested_children(db, child))
    selected = next((row for row in all_children if row.id == selected_id), None) if selected_id is not None else None
    if selected_id is not None and (selected is None or selected.status not in ('failed', 'canceled')):
        raise error('invalid_retry_item', '只能重试当前子编排清单中失败或取消的项。', 422)
    retry_source = {
        row.id for row in all_children
        if row.status in ('failed', 'canceled') and (selected_id is None or row.id == selected_id or row.error_code == 'subgraph_sibling_failed')
    }
    if not retry_source:
        raise error('invalid_retry_item', '当前子编排没有可重试的失败项。', 422)
    from app.tasks.fanout import node_record_usage
    # Every child is cloned to preserve immutable parent ownership, including
    # successful siblings. Reserve the new control and its final aggregate too.
    if node_record_usage(db, run.id) + len(all_children) + 2 > 500:
        raise error('storage_limit_exceeded', '运行超过 500 条尝试限制。', 422)
    retry = NodeRun(
        run_id=run.id, node_id=control.node_id, iteration=control.iteration,
        attempt=control.attempt + 1, execution_kind='node', status='running', input_json='{}',
    )
    db.add(retry)
    db.flush()
    clones = {}

    def clone_nested(prior, parent_id, *, retry=False):
        state = json.loads(prior.input_json)
        clone = NodeRun(
            run_id=run.id, node_id=prior.node_id, iteration=prior.iteration,
            attempt=prior.attempt + 1, execution_kind='subgraph_node', foreach_index=prior.foreach_index,
            input_json=encoded({**state, 'subgraph_parent_node_run_id': parent_id, 'reused_from': prior.id,
                                **({'retry_of': prior.id} if retry else {})}),
            status='idle' if retry else prior.status,
            output_json=None if retry else prior.output_json,
            error_code=None if retry else prior.error_code,
            started_at=None if retry else prior.started_at,
            finished_at=None if retry else prior.finished_at,
        )
        db.add(clone)
        db.flush()
        clones[prior.id] = clone
        return clone

    new_children = []
    new_retry_ids = []
    for child in children:
        child_state = json.loads(child.input_json)
        nested_ids = child_state.get('nested_subgraph_node_run_ids', [])
        nested = [db.get(NodeRun, identity) for identity in nested_ids]
        nested_retry = any(row is not None and row.id in retry_source for row in nested)
        if not nested_ids:
            clone = clone_nested(child, retry.id, retry=child.id in retry_source)
            new_children.append(clone)
            if child.id in retry_source:
                new_retry_ids.append(clone.id)
            continue
        if any(row is None or row.run_id != run.id or row.execution_kind != 'subgraph_node' for row in nested):
            raise error('invalid_retry_item', '来源子编排清单不可用。', 422)
        outer_retry = child.id in retry_source or nested_retry
        outer = clone_nested(child, retry.id, retry=outer_retry)
        outer_state = json.loads(outer.input_json)
        nested_manifest, nested_retry_ids = [], []
        for leaf in nested:
            leaf_retry = leaf.id in retry_source or child.id in retry_source
            clone = clone_nested(leaf, outer.id, retry=leaf_retry)
            nested_manifest.append(clone.id)
            if leaf_retry:
                nested_retry_ids.append(clone.id)
        outer_state['nested_subgraph_node_run_ids'] = nested_manifest
        outer_state['nested_retry_subgraph_node_run_ids'] = nested_retry_ids
        outer.input_json = encoded(outer_state)
        outer.status = 'running' if outer_retry else outer.status
        new_children.append(outer)
        if outer_retry:
            new_retry_ids.append(outer.id)
    state = json.loads(control.input_json)
    state['subgraph_node_run_ids'] = [row.id for row in new_children]
    state['subgraph_aggregate_node_run_id'] = None
    state['retry_subgraph_node_run_ids'] = new_retry_ids
    retry.input_json = encoded(state)
    return retry


def _dynamic_values(value, config):
    """Decode exactly once and validate a bounded local DAG."""
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except (TypeError, ValueError):
            return None
    if not isinstance(value, list) or len(value) > config['max_nodes'] or not graph_valid(value):
        return None
    return value


def _dynamic_ready(children, condition_matches, now):
    by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in children}
    ready, changed = [], False
    for child in children:
        if child.status != 'idle':
            continue
        state = json.loads(child.input_json)
        dynamic_node = state.get('dynamic_node', {})
        deps = [by_id[identity] for identity in dynamic_node.get('deps', [])]
        if not all(dep.status == 'succeeded' or (dep.status == 'skipped' and dynamic_node.get('allow_missing_inputs')) for dep in deps):
            continue
        condition = dynamic_node.get('condition')
        if condition:
            source = by_id[condition['source']]
            output = json.loads(source.output_json) if source.output_json else None
            if not condition_matches(condition, output):
                child.status, child.error_code, child.finished_at = 'skipped', 'condition_not_matched', now
                changed = True
                continue
        ready.append(child)
    return ready, changed


def advance_subgraphs(db, run, definition, rows, *, encoded, value_at_path=None,
                      condition_matches=None, now=None):
    """Return child dispatch candidates and whether a durable transition occurred."""
    now = now or datetime.now(timezone.utc)
    candidates, changed = [], False
    for item in definition['nodes']:
        config = item.get('subgraph')
        if not config:
            continue
        control = rows[item['id']]
        if control.status not in ('idle', 'running'):
            continue
        state = json.loads(control.input_json)
        children = _children(db, control) if state.get('subgraph_node_run_ids') else []
        if control.status == 'idle' and not children:
            if any(rows[dep].status != 'succeeded' for dep in item.get('deps', [])):
                continue
            dynamic = config.get('dynamic')
            dynamic_nodes = config.get('nodes', [])
            dynamic_snapshot = None
            run_snapshot = json.loads(run.snapshot_json)
            if dynamic is not None:
                source = rows[dynamic['source']]
                source_output = json.loads(source.output_json) if source.output_json else None
                value = value_at_path(source_output, dynamic['path']) if value_at_path else None
                dynamic_snapshot = _dynamic_values(value, dynamic)
                if dynamic_snapshot is None:
                    control.status, control.error_code, control.finished_at = 'failed', 'subgraph_dynamic_invalid', now
                    return candidates, True
                binding = execution_binding(run_snapshot, item.get('agent_id'), item.get('model'))
                dynamic_nodes = [{**child, 'agent_id': item.get('agent_id'), 'model': item.get('model'),
                                  'execution_binding': binding}
                                 for child in dynamic_snapshot]
            from app.tasks.fanout import node_record_usage
            if node_record_usage(db, run.id) + len(dynamic_nodes) + 1 > 500:
                control.status, control.error_code, control.finished_at = 'failed', 'storage_limit_exceeded', now
                changed = True
                continue
            parent_refs = [{'id': ref, 'node_run_id': rows[ref].id, 'output': json.loads(rows[ref].output_json)}
                           for ref in item.get('inputRefs', []) if rows[ref].status == 'succeeded' and rows[ref].output_json]
            created = []
            for index, child in enumerate(dynamic_nodes):
                child_row = NodeRun(
                    run_id=run.id, node_id=item['id'], iteration=control.iteration,
                    attempt=1, execution_kind='subgraph_node', foreach_index=index,
                    input_json=encoded({'_orchestration_role': 'subgraph_node',
                                        'subgraph_node_id': child['id'],
                                        'subgraph_parent_node_run_id': control.id,
                                        'subgraph_index': index,
                                        'prompt': child.get('prompt', ''),
                                        'inputRefs': child.get('inputRefs', []),
                                        'deps': child.get('deps', []),
                                        'parent_refs': parent_refs,
                                        **({'execution_binding': child.get('execution_binding')} if child.get('execution_binding')
                                           else {'execution_binding': execution_binding(run_snapshot,
                                                                                         child.get('agent_id'),
                                                                                         child.get('model'))}),
                                        **({'dynamic': True, 'dynamic_node': child,
                                            'dynamic_parent_prompt': item.get('prompt', '')}
                                           if dynamic is not None else {}),
                                        **({'nested_subgraph': child['subgraph']} if child.get('subgraph') else {})}),
                )
                db.add(child_row)
                db.flush()
                created.append(child_row)
            state = {**state, '_orchestration_role': 'subgraph_control',
                     'subgraph_node_run_ids': [row.id for row in created],
                     'subgraph_aggregate_node_run_id': None,
                     **({'dynamic': True, 'dynamic_source': dynamic['source'],
                         'dynamic_path': dynamic['path'], 'dynamic_nodes': dynamic_nodes} if dynamic is not None else {})}
            control.input_json = encoded(state)
            control.status, control.started_at = 'running', control.started_at or now
            changed = True
            children = created
        if control.status not in ('idle', 'running'):
            continue
        retry_ids = set(state.get('retry_subgraph_node_run_ids', []))
        retry_pending = any(row.id in retry_ids and row.status in ('idle', 'running') for row in children)
        failed = next((row for row in children if row.status in ('failed', 'canceled')
                       and (not retry_pending or row.id in retry_ids)), None)
        if failed:
            for row in children:
                if row.status == 'idle':
                    row.status, row.error_code, row.finished_at = 'canceled', 'subgraph_sibling_failed', now
            control.status, control.error_code, control.finished_at = 'failed', 'subgraph_child_failed', now
            changed = True
            continue
        # Share one ready selection across normal children and nested controls.
        # Nested leaves are later scheduled inside their own scope.
        admitted = []
        if not state.get('dynamic'):
            admitted = _static_ready(children, config.get('max_concurrency', 1))
        for child in children:
            child_state = json.loads(child.input_json)
            nested_config = child_state.get('nested_subgraph')
            if not nested_config or child.status not in ('idle', 'running'):
                continue
            nested_ids = child_state.get('nested_subgraph_node_run_ids')
            nested_rows = _nested_children(db, child) if nested_ids else []
            if child.status == 'idle' and not nested_rows:
                if child not in admitted:
                    continue
                from app.tasks.fanout import node_record_usage
                if node_record_usage(db, run.id) + len(nested_config['nodes']) > 500:
                    child.status, child.error_code, child.finished_at = 'failed', 'storage_limit_exceeded', now
                    changed = True
                    continue
                nested_created = []
                run_snapshot = json.loads(run.snapshot_json)
                for nested_index, nested in enumerate(nested_config['nodes']):
                    nested_row = NodeRun(
                        run_id=run.id, node_id=item['id'], iteration=child.iteration,
                        attempt=1, execution_kind='subgraph_node', foreach_index=nested_index,
                        input_json=encoded({'_orchestration_role': 'subgraph_node',
                                            'subgraph_node_id': nested['id'],
                                            'subgraph_parent_node_run_id': child.id,
                                            'subgraph_index': nested_index,
                                            'inputRefs': nested.get('inputRefs', []),
                                            'deps': nested.get('deps', []),
                                            'parent_refs': child_state.get('parent_refs', []) + _refs(children, child_state),
                                            'nested_subgraph_parent': True,
                                            'nested_parent_node_id': child_state.get('subgraph_node_id'),
                                            'nested_prompt_prefix': child_state.get('prompt', ''),
                                            'execution_binding': execution_binding(run_snapshot,
                                                                                   nested.get('agent_id'),
                                                                                   nested.get('model'))}),
                    )
                    db.add(nested_row)
                    db.flush()
                    nested_created.append(nested_row)
                child_state['nested_subgraph_node_run_ids'] = [row.id for row in nested_created]
                child.input_json = encoded(child_state)
                child.status, child.started_at = 'running', child.started_at or now
                changed = True
                nested_rows = nested_created
            if child.status not in ('idle', 'running'):
                continue
            nested_failed = next((row for row in nested_rows if row.status in ('failed', 'canceled')), None)
            nested_retry_ids = set(child_state.get('nested_retry_subgraph_node_run_ids', []))
            nested_retry_pending = any(row.id in nested_retry_ids and row.status in ('idle', 'running') for row in nested_rows)
            if nested_failed:
                if nested_retry_pending:
                    continue
                for row in nested_rows:
                    if row.status == 'idle':
                        row.status, row.error_code, row.finished_at = 'canceled', 'subgraph_sibling_failed', now
                child.status, child.error_code, child.finished_at = 'failed', 'subgraph_child_failed', now
                changed = True
                continue
            if nested_rows and all(row.status in ('succeeded', 'skipped') for row in nested_rows):
                output = encoded({'nodes': _manifest_output(nested_rows), 'status': 'completed'})
                if len(output.encode('utf-8')) > 1024 * 1024:
                    child.status, child.error_code, child.finished_at = 'failed', 'storage_limit_exceeded', now
                    changed = True
                    continue
                child.output_json = output
                child.status, child.finished_at = 'succeeded', now
                changed = True
                continue
            nested_config_by_id = {nested['id']: nested for nested in nested_config['nodes']}
            # A nested static scope has its own bounded scheduler.  The outer
            # workflow executor still applies its global max_concurrency when
            # it truncates the combined candidate list.
            nested_idle = _static_ready(nested_rows, nested_config.get('max_concurrency', 1))
            nested_candidates = [( 'subgraph_node', nested_config_by_id[json.loads(row.input_json)['subgraph_node_id']], row)
                                 for row in nested_idle]
            candidates.extend(nested_candidates)
            continue
        is_dynamic = bool(state.get('dynamic'))
        if (is_dynamic and not children) or (children and all(row.status in ('succeeded', 'skipped') for row in children)):
            aggregate_id = state.get('subgraph_aggregate_node_run_id')
            aggregate = db.get(NodeRun, aggregate_id) if aggregate_id else None
            if aggregate is None:
                output = encoded({'nodes': _manifest_output(children), 'status': 'completed'})
                if len(output.encode('utf-8')) > 1024 * 1024:
                    control.status, control.error_code, control.finished_at = 'failed', 'storage_limit_exceeded', now
                    changed = True
                    continue
                aggregate = NodeRun(run_id=run.id, node_id=item['id'], iteration=control.iteration,
                                    attempt=control.attempt, execution_kind='subgraph_aggregate',
                                    input_json=encoded({'_orchestration_role': 'subgraph_aggregate',
                                                        'subgraph_parent_node_run_id': control.id,
                                                        'subgraph_node_run_ids': [row.id for row in children],
                                                        'item_count': len(children)}),
                                    output_json=output,
                                    status='succeeded', started_at=control.started_at or now, finished_at=now)
                db.add(aggregate)
                db.flush()
                state['subgraph_aggregate_node_run_id'] = aggregate.id
                control.input_json = encoded(state)
            control.output_json = aggregate.output_json
            control.status, control.finished_at = 'succeeded', now
            changed = True
            continue
        by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in children}
        if is_dynamic and condition_matches:
            idle, graph_changed = _dynamic_ready(children, condition_matches, now)
            if graph_changed:
                changed = True
                continue
            if not idle and not any(row.status == 'running' for row in children):
                control.status, control.error_code, control.finished_at = 'failed', 'subgraph_dynamic_dependency_unavailable', now
                changed = True
                continue
        else:
            idle = [child for child in admitted
                    if not json.loads(child.input_json).get('nested_subgraph')]
        mode = config.get('dynamic', {}).get('mode', 'serial') if is_dynamic else 'parallel' if config.get('max_concurrency', 1) > 1 else 'serial'
        if mode == 'serial':
            idle = idle[:1]
        elif is_dynamic:
            running = sum(row.status == 'running' for row in children)
            idle = idle[:max(0, config['max_concurrency'] - running)]
        child_by_id = ({child['id']: child for child in state.get('dynamic_nodes', [])}
                       if is_dynamic else {child['id']: child for child in config['nodes']})
        candidates.extend([('subgraph_node', child_by_id[json.loads(row.input_json)['subgraph_node_id']], row)
                           for row in idle])
    return candidates, changed
