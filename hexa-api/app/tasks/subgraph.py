"""Bounded static subgraphs owned by a parent NodeRun.

The child graph is copied into the Run snapshot and materialized once. It is
never generated by the model and cannot contain another control construct.
"""
import json
from datetime import datetime, timezone

from app.db.models import NodeRun


def _children(db, control):
    state = json.loads(control.input_json)
    ids = state.get('subgraph_node_run_ids', [])
    rows = [db.get(NodeRun, identity) for identity in ids]
    if any(row is None or row.run_id != control.run_id or row.node_id != control.node_id
            or row.iteration != control.iteration or row.execution_kind != 'subgraph_node'
           for row in rows):
        raise ValueError('invalid persisted subgraph manifest')
    return rows


def _refs(rows, child_state):
    by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in rows}
    result = []
    for identity in child_state.get('inputRefs', []):
        row = by_id.get(identity)
        if row and row.status == 'succeeded' and row.output_json:
            result.append({'id': identity, 'node_run_id': row.id, 'output': json.loads(row.output_json)})
    return result


def _manifest_output(rows):
    return [{'id': json.loads(row.input_json)['subgraph_node_id'], 'status': row.status,
             **({'output': json.loads(row.output_json)} if row.output_json else {}),
             **({'error_code': row.error_code} if row.error_code else {})} for row in rows]


def advance_subgraphs(db, run, definition, rows, *, encoded, now=None):
    """Return child dispatch candidates and whether a durable transition occurred."""
    now = now or datetime.now(timezone.utc)
    candidates, changed = [], False
    for item in definition['nodes']:
        config = item.get('subgraph')
        if not config:
            continue
        control = rows[item['id']]
        if control.status not in ('idle', 'running'):
            continue
        state = json.loads(control.input_json)
        children = _children(db, control) if state.get('subgraph_node_run_ids') else []
        if control.status == 'idle' and not children:
            if any(rows[dep].status != 'succeeded' for dep in item.get('deps', [])):
                continue
            from app.tasks.fanout import node_record_usage
            if node_record_usage(db, run.id) + len(config['nodes']) + 1 > 500:
                control.status, control.error_code, control.finished_at = 'failed', 'storage_limit_exceeded', now
                changed = True
                continue
            parent_refs = [{'id': ref, 'node_run_id': rows[ref].id, 'output': json.loads(rows[ref].output_json)}
                           for ref in item.get('inputRefs', []) if rows[ref].status == 'succeeded' and rows[ref].output_json]
            created = []
            for index, child in enumerate(config['nodes']):
                child_row = NodeRun(
                    run_id=run.id, node_id=item['id'], iteration=control.iteration,
                    attempt=1, execution_kind='subgraph_node', foreach_index=index,
                    input_json=encoded({'_orchestration_role': 'subgraph_node',
                                        'subgraph_node_id': child['id'],
                                        'subgraph_parent_node_run_id': control.id,
                                        'subgraph_index': index,
                                        'inputRefs': child.get('inputRefs', []),
                                        'deps': child.get('deps', []),
                                        'parent_refs': parent_refs}),
                )
                db.add(child_row)
                db.flush()
                created.append(child_row)
            state = {**state, '_orchestration_role': 'subgraph_control',
                     'subgraph_node_run_ids': [row.id for row in created],
                     'subgraph_aggregate_node_run_id': None}
            control.input_json = encoded(state)
            control.status, control.started_at = 'running', control.started_at or now
            changed = True
            children = created
        if control.status not in ('idle', 'running'):
            continue
        failed = next((row for row in children if row.status in ('failed', 'canceled')), None)
        if failed:
            for row in children:
                if row.status == 'idle':
                    row.status, row.error_code, row.finished_at = 'canceled', 'subgraph_sibling_failed', now
            control.status, control.error_code, control.finished_at = 'failed', 'subgraph_child_failed', now
            changed = True
            continue
        if children and all(row.status == 'succeeded' for row in children):
            aggregate_id = state.get('subgraph_aggregate_node_run_id')
            aggregate = db.get(NodeRun, aggregate_id) if aggregate_id else None
            if aggregate is None:
                aggregate = NodeRun(run_id=run.id, node_id=item['id'], iteration=control.iteration,
                                    attempt=control.attempt, execution_kind='subgraph_aggregate',
                                    input_json=encoded({'_orchestration_role': 'subgraph_aggregate',
                                                        'subgraph_parent_node_run_id': control.id,
                                                        'subgraph_node_run_ids': [row.id for row in children],
                                                        'item_count': len(children)}),
                                    output_json=encoded({'nodes': _manifest_output(children), 'status': 'completed'}),
                                    status='succeeded', started_at=control.started_at or now, finished_at=now)
                db.add(aggregate)
                db.flush()
                state['subgraph_aggregate_node_run_id'] = aggregate.id
                control.input_json = encoded(state)
            control.output_json = aggregate.output_json
            control.status, control.finished_at = 'succeeded', now
            changed = True
            continue
        by_id = {json.loads(row.input_json)['subgraph_node_id']: row for row in children}
        idle = []
        for child in children:
            if child.status != 'idle':
                continue
            child_state = json.loads(child.input_json)
            deps = [by_id[identity] for identity in child_state.get('deps', [])]
            if all(dep.status == 'succeeded' for dep in deps):
                idle.append(child)
        if config.get('max_concurrency', 1) == 1:
            idle = idle[:1]
        else:
            running = sum(row.status == 'running' for row in children)
            idle = idle[:max(0, config['max_concurrency'] - running)]
        child_by_id = {child['id']: child for child in config['nodes']}
        candidates.extend([('subgraph_node', child_by_id[json.loads(row.input_json)['subgraph_node_id']], row)
                           for row in idle])
    return candidates, changed
