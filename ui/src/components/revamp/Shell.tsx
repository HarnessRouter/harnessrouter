export function Shell({ children, credits }: { children: React.ReactNode; credits?: number | null }) {
  const pathname = usePathname() || '';
  const router = useRouter();
  const { workspaces, current, setCurrent, create } = useWorkspace();
  const [wsMenu, setWsMenu] = useState(false);
  const [wsCreate, setWsCreate] = useState(false);
  const [wsName, setWsName] = useState('');
  const [wsDesc, setWsDesc] = useState('');
  const [wsBusy, setWsBusy] = useState(false);
  const [wsErr, setWsErr] = useState('');
  const [acctMenu, setAcctMenu] = useState(false);
  // Not a build-time constant: the image is built once and credentials are set when it runs.
  const [selfHostUser, setSelfHostUser] = useState('');
  useEffect(() => {
    if (!SELF_HOSTED) return;
    fetch('/api/selfhost/session')
      .then((r) => (r.ok ? r.json() : null))
      .then((d) => { if (d?.user) setSelfHostUser(String(d.user)); })
      .catch(() => { /* the menu just says "this instance" */ });
  }, []);
  const [mobileNav, setMobileNav] = useState(false);
  // Quickstart progress rides on its sidebar entry until all four steps are done.
  const [qs] = useQuickstart();
  const qsDone = quickstartDone(qs);
  // v2 resizable sidebar: drag 64-340, release under 150 snaps to the 64px icon rail,
  // double-click toggles. Width persists per browser; expanded = navW >= 150 (the design's rule).
  const [navW, setNavW] = useState(268);
  const [dragging, setDragging] = useState(false);
  const dragRef = useRef({ startX: 0, startW: 268 });
  useEffect(() => {
    try {
      const saved = Number(localStorage.getItem('hr.v2.navW') || '');
      if (saved >= 64 && saved <= 340) setNavW(saved < 150 ? 64 : saved);
      // Tablet default: below 1025 the rail is the right starting point.
      else if (window.innerWidth <= 1024) setNavW(64);
    } catch { /* storage unavailable -> keep the default */ }
  }, []);
  const commitNavW = useCallback((w: number) => {
    const snapped = w < 150 ? 64 : Math.min(340, Math.max(150, w));
    setNavW(snapped);
    try { localStorage.setItem('hr.v2.navW', String(snapped)); } catch { /* ignore */ }
  }, []);
  const onDragStart = useCallback((e: React.PointerEvent) => {
    dragRef.current = { startX: e.clientX, startW: navW };
    setDragging(true);
    const move = (ev: PointerEvent) => {
      const w = dragRef.current.startW + (ev.clientX - dragRef.current.startX);
      setNavW(Math.min(340, Math.max(64, w)));
    };
    const up = (ev: PointerEvent) => {
      window.removeEventListener('pointermove', move);
      window.removeEventListener('pointerup', up);
      setDragging(false);
      commitNavW(dragRef.current.startW + (ev.clientX - dragRef.current.startX));
    };
    window.addEventListener('pointermove', move);
    window.addEventListener('pointerup', up);
  }, [navW, commitNavW]);
  // The icon rail is a desktop preference. On a phone the sidebar is a drawer, and a drawer is
  // always the full nav: labels, group headings, the workspace card. The stored width still
  // applies the moment the viewport is wide again.
  const [mobile, setMobile] = useState(false);
  useEffect(() => {
    const mq = window.matchMedia('(max-width: 768px)');
    const sync = () => setMobile(mq.matches);
    sync(); mq.addEventListener('change', sync);
    return () => mq.removeEventListener('change', sync);
  }, []);
  const railed = navW < 150 && !mobile;
  // The width variable must live on the ROOT, not on the aside: .v2-main is a sibling, and a
  // custom property set inline on the aside never cascades to it — so the content margin stayed
  // 268px with the rail collapsed, leaving exactly the dead gap the owner screenshotted.
  useEffect(() => {
    document.documentElement.style.setProperty('--v2-navw', `${navW}px`);
    return () => { document.documentElement.style.removeProperty('--v2-navw'); };
  }, [navW]);
  const [connectOpen, setConnectOpen] = useState(false);
  const wsRef = useRef<HTMLDivElement>(null);
  const acctRef = useRef<HTMLDivElement>(null);
  const connectRef = useRef<HTMLDivElement>(null);
  const mainRef = useRef<HTMLElement>(null);

  // Global search, matches workspaces (from context), and this workspace's harnesses + tasks
  // (loaded lazily on first focus, then filtered client-side). Substring, case-insensitive.
  const [searchOpen, setSearchOpen] = useState(false);
  const [query, setQuery] = useState('');
  const [activeIdx, setActiveIdx] = useState(0);
  const [harnesses, setHarnesses] = useState<{ id: string; name: string }[] | null>(null);
  const [tasks, setTasks] = useState<TraceCard[] | null>(null);
  const [searchLoading, setSearchLoading] = useState(false);
  const searchRef = useRef<HTMLDivElement>(null);
  const searchInputRef = useRef<HTMLInputElement>(null);
  const searchLoaded = useRef(false);

  const ensureSearchData = useCallback(async () => {
    if (searchLoaded.current) return;
    searchLoaded.current = true;
    setSearchLoading(true);
    try {
      const [h, t] = await Promise.all([
        listCustom().catch(() => []),
        fetchTraceWindow().catch(() => []),
      ]);
      // Search spans the built-in (default) harnesses AND the workspace's custom ones; the base
      // catalog also names tasks whose trace card carries only a base harness id (e.g. Codex).
      setHarnesses([...OOB.map((o) => ({ id: o.id, name: o.name })), ...h.map((c) => ({ id: c.id, name: c.name }))]);
      setTasks(t);
    } finally { setSearchLoading(false); }
  }, []);

  const q = query.trim().toLowerCase();
  const groups = useMemo(() => {
    if (!q) return null;
    // harness_name is missing on older trace cards; resolve it from the loaded harness list
    // (id -> name), which is how the Overview tables label tasks too.
    const hname = new Map((harnesses || []).map((h) => [h.id, h.name]));
    const ws = workspaces
      .filter((w) => w.name.toLowerCase().includes(q))
      .slice(0, MAX_PER_GROUP)
      .map((w): SearchItem => ({ kind: 'workspace', id: w.id, label: w.name, sub: w.description, current: w.id === current.id }));
    const hs = (harnesses || [])
      .filter((h) => h.name.toLowerCase().includes(q))
      .slice(0, MAX_PER_GROUP)
      .map((h): SearchItem => ({ kind: 'harness', id: h.id, label: h.name }));
    const ts = (tasks || [])
      .filter((t) => taskLabel(t).toLowerCase().includes(q) || (t.session_id || '').toLowerCase().includes(q))
      .slice(0, MAX_PER_GROUP)
      .map((t): SearchItem => ({ kind: 'task', sid: t.session_id, harnessId: t.harness_id, label: taskLabel(t), sub: (t.harness_id && hname.get(t.harness_id)) || t.harness_name || undefined }));
    return { ws, hs, ts };
  }, [q, workspaces, harnesses, tasks, current.id]);
  const flat = useMemo(() => (groups ? [...groups.ws, ...groups.hs, ...groups.ts] : []), [groups]);

  // Reset the keyboard cursor whenever the result set changes.
  useEffect(() => { setActiveIdx(0); }, [q, flat.length]);

  const openItem = useCallback((it: SearchItem) => {
    setSearchOpen(false);
    setQuery('');
    searchInputRef.current?.blur();
    if (it.kind === 'workspace') {
      if (it.current) return;
      setCurrent(it.id);
      // Match the switcher: hard reload so every workspace-scoped surface re-queries, and
      // without the query string, so a record from the old workspace does not stay open.
      window.location.assign(window.location.pathname);
      return;
    }
    if (it.kind === 'harness') { router.push(`/harnesses/${encodeURIComponent(it.id)}`); return; }
    const p = new URLSearchParams();
    if (it.harnessId) p.set('h', it.harnessId);
    p.set('sid', it.sid);
    // Hard nav (not router.push): the workbench binds its deep-linked task on mount, so when the
    // user is already on /tasks a client-side query swap changes the URL but doesn't reopen the
    // task. A full load remounts the workbench and opens the exact task every time.
    window.location.assign(`/harnesses?${p.toString()}`);
  }, [router, setCurrent]);

  const onSearchKey = (e: React.KeyboardEvent) => {
    if (e.key === 'ArrowDown') { e.preventDefault(); setSearchOpen(true); setActiveIdx((i) => Math.min(i + 1, flat.length - 1)); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); setActiveIdx((i) => Math.max(i - 1, 0)); }
    else if (e.key === 'Enter') { const it = flat[activeIdx]; if (it) { e.preventDefault(); openItem(it); } }
    else if (e.key === 'Escape') { setSearchOpen(false); searchInputRef.current?.blur(); }
  };

  // ⌘K / Ctrl+K focuses search from anywhere.
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && (e.key === 'k' || e.key === 'K')) {
        e.preventDefault();
        setSearchOpen(true);
        searchInputRef.current?.focus();
        void ensureSearchData();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [ensureSearchData]);

  // main is the scroll container (not the document), start each page at its top,
  // otherwise client-side nav lands mid-scroll on the next page.
  useEffect(() => { mainRef.current?.scrollTo(0, 0); }, [pathname]);

  async function submitCreate(e: React.FormEvent) {
    e.preventDefault();
    if (!wsName.trim() || wsBusy) return;
    setWsBusy(true); setWsErr('');
    try {
      await create(wsName.trim(), wsDesc.trim());
      setWsCreate(false); setWsName(''); setWsDesc('');
      // Per the design: after creation, Quickstart opens so the user connects a coding agent
      // and mints the first Workspace API Key. Hard nav so every surface re-queries under the
      // new workspace scope.
      window.location.assign('/quickstart');
    } catch (ex) { setWsErr(ex instanceof Error ? ex.message : 'create failed'); }
    finally { setWsBusy(false); }
  }

  useEffect(() => {
    const close = (e: MouseEvent) => {
      if (wsRef.current && !wsRef.current.contains(e.target as Node)) setWsMenu(false);
      if (acctRef.current && !acctRef.current.contains(e.target as Node)) setAcctMenu(false);
      if (connectRef.current && !connectRef.current.contains(e.target as Node)) setConnectOpen(false);
      if (searchRef.current && !searchRef.current.contains(e.target as Node)) setSearchOpen(false);
    };
    document.addEventListener('mousedown', close);
    return () => document.removeEventListener('mousedown', close);
  }, []);
  useEffect(() => { setMobileNav(false); setSearchOpen(false); }, [pathname]);

  const s = getSession();
  const initials = SELF_HOSTED
    ? (selfHostUser || '?').slice(0, 2).toUpperCase()
    : (s?.member?.name || s?.member?.email || '?').slice(0, 2).toUpperCase();
  const avatarUrl = SELF_HOSTED ? '' : ((s?.member?.avatar_url as string) || '');
  const acctLabel = SELF_HOSTED ? (selfHostUser || 'This instance') : (s?.member?.email || 'Account');
  const isActive = (href: string) => pathname === href || pathname.startsWith(href + '/');

  const renderGroup = (title: string, icon: string, items: SearchItem[], offset: number) => {
    if (!items.length) return null;
    return (
      <div className="search-group">
        <p className="search-group-label">{title}</p>
        {items.map((it, i) => {
          const idx = offset + i;
          const active = idx === activeIdx;
          const key = it.kind === 'task' ? `task:${it.sid}` : `${it.kind}:${it.id}`;
          const isCurrentWs = it.kind === 'workspace' && it.current;
          return (
            <button key={key} type="button" role="option" aria-selected={active}
              className={'search-item' + (active ? ' is-active' : '')}
              onMouseEnter={() => setActiveIdx(idx)}
              onMouseDown={(e) => e.preventDefault()}
              onClick={() => openItem(it)}>
              <iconify-icon icon={icon} aria-hidden="true"></iconify-icon>
              <span className="search-item-main">
                <span className="search-item-label">{highlight(it.label, q)}</span>
                {it.sub ? <span className="search-item-sub">{it.sub}</span> : null}
              </span>
              {isCurrentWs
                ? <span className="search-item-tag">Current</span>
                : active ? <iconify-icon className="search-item-go" icon="tabler:corner-down-left" aria-hidden="true"></iconify-icon> : null}
            </button>
          );
        })}
      </div>
    );
  };

  return (
    <>
      {/* mobile top bar (<=768): brand + hamburger; the sidebar becomes an overlay drawer */}
      <div className="v2-mobilebar">
        {/* eslint-disable-next-line @next/next/no-img-element -- small static brand asset */}
        <img src="/harnessrouter-logo.svg" alt="" />
        <strong>HarnessRouter Console</strong>
        <button type="button" aria-label="Open navigation" aria-expanded={mobileNav}
          onClick={() => setMobileNav((v) => !v)}><iconify-icon icon="tabler:menu-2"></iconify-icon></button>
      </div>

      <aside className={'v2-side' + (railed ? ' is-rail' : '') + (dragging ? ' is-dragging' : '') + (mobileNav ? ' is-open' : '')}
        style={{ ['--v2-navw' as string]: `${navW}px` }} aria-label="Product navigation">
        <div className="v2-resize" role="separator" aria-orientation="vertical" aria-label="Resize navigation"
          onPointerDown={onDragStart} onDoubleClick={() => commitNavW(railed ? 268 : 64)} />

        <div className="v2-title">
          {/* Expanded: the full wordmark, nothing else (no "Console" suffix). Rail: icon only.
              eslint-disable-next-line @next/next/no-img-element -- small static brand asset */}
          <span className="v2-brand">
            {/* eslint-disable-next-line @next/next/no-img-element -- small static brand asset */}
            <img className="v2-brand-full" src="/harnessrouter-wordmark.png" alt="HarnessRouter" />
            {/* eslint-disable-next-line @next/next/no-img-element -- small static brand asset */}
            <img className="v2-brand-icon" src="/harnessrouter-logo.svg" alt="HarnessRouter" />
          </span>
          <span className="v2-title-actions">
            {/* The explicit collapse/expand toggle from the design's title row. Search moved out
                of this row entirely (it crowded the brand) - Cmd+K still opens the palette. */}
            <button className="v2-collapsebtn" type="button"
              aria-label={railed ? 'Expand navigation' : 'Collapse navigation'}
              title={railed ? 'Expand navigation' : 'Collapse navigation (or press Cmd+K to search)'}
              onClick={() => commitNavW(railed ? 268 : 64)}>
              <iconify-icon icon="tabler:layout-sidebar"></iconify-icon>
            </button>
          </span>
        </div>

        {SELF_HOSTED ? null : (
        <div className="switcher-wrap" ref={wsRef}>
          <button className="v2-wscard" type="button" aria-expanded={wsMenu} onClick={() => setWsMenu((v) => !v)}
            title={railed ? current.name : undefined}>
            <span className="v2-wsavatar">{(current.name || '?').slice(0, 2).toUpperCase()}</span>
            <span className="v2-wsmeta">
              <span className="v2-wskicker">Workspace</span>
              <span className="v2-wsname">{current.name}</span>
            </span>
            <iconify-icon icon="tabler:selector" className="v2-wschev"></iconify-icon>
          </button>
          {wsMenu && (
            <div className="workspace-menu">
              {workspaces.map((w) => (
                <button key={w.id} className="workspace-menu-item" type="button"
                  aria-current={w.id === current.id}
                  onClick={() => {
                    setWsMenu(false);
                    if (w.id !== current.id) {
                      setCurrent(w.id);
                      // Every data surface scopes reads by the active workspace, hard refresh so
                      // long-lived client caches (recents polls, dashboards) re-query cleanly. The
                      // query string is dropped on purpose: an open arena or task belongs to the
                      // workspace it was made in, not to the one just chosen.
                      window.location.assign(window.location.pathname);
                    }
                  }}>
                  <span>{w.name}</span>
                  {w.id === current.id && <iconify-icon icon="tabler:check"></iconify-icon>}
                </button>
              ))}
              <div className="workspace-menu-separator"></div>
              <button className="workspace-menu-item" type="button"
                onClick={() => { setWsMenu(false); router.push('/settings'); }}>
                <span><iconify-icon icon="tabler:settings"></iconify-icon> Workspace settings</span>
              </button>
              <button className="workspace-menu-item" type="button"
                onClick={() => { setWsMenu(false); setWsCreate(true); setWsErr(''); }}>
                <span><iconify-icon icon="tabler:plus"></iconify-icon> Create Workspace</span>
              </button>
            </div>
          )}
        </div>
        )}

        <nav className="v2-nav">
          {NAV_GROUPS.map((g, gi) => (
            <div key={gi} className="v2-group">
              {g.label ? <p className="v2-group-label">{g.label}</p> : null}
              {g.items.map((n) => n.soon ? (
                <span key={n.label} className="v2-item is-soon" title={railed ? `${n.label} (soon)` : undefined}>
                  <iconify-icon icon={n.icon || ''}></iconify-icon><span>{n.label}</span>
                  <span className="v2-soon-pill">soon</span>
                </span>
              ) : (
                <Link key={n.href} className="v2-item" href={n.href!} title={railed ? n.label : undefined}
                  aria-current={isActive(n.href!) ? 'page' : undefined}>
                  {n.img
                    /* eslint-disable-next-line @next/next/no-img-element -- small static brand asset */
                    ? <img className="v2-item-img" src={n.img} alt="" aria-hidden="true" />
                    : <iconify-icon icon={n.icon || ''}></iconify-icon>}
                  <span>{n.label}</span>
                  {n.href === '/quickstart' && qsDone < 4 && <span className="v2-item-badge" aria-label={`${qsDone} of 4 steps done`}>{qsDone}/4</span>}
                </Link>
              ))}
            </div>
          ))}
          {SELF_HOSTED ? null : (
          <div className="v2-group">
            <p className="v2-group-label">Billing</p>
            <Link className="v2-item" href="/billing" title={railed ? 'Credits' : undefined}
              aria-current={isActive('/billing') ? 'page' : undefined}
              aria-label={credits != null ? `Credits, balance ${credits}` : 'Credits'}>
              {/* Coins, not a dollar sign: credits are not currency and must not look like it. */}
              <iconify-icon icon="tabler:coins"></iconify-icon><span>Credits</span>
              <span className="v2-item-end">{credits != null ? credits.toLocaleString() : '—'}</span>
            </Link>
          </div>
          )}
          {PLATFORM_NAV.filter((n) => (SELF_HOSTED
            ? SELF_HOSTED_NAV.includes(n.href)     // your own keys, on your own box
            : n.orgs.includes(s?.orgId || ''))).length > 0 && (
            <div className="v2-group">
              <p className="v2-group-label">Platform</p>
              {PLATFORM_NAV.filter((n) => (SELF_HOSTED
                ? SELF_HOSTED_NAV.includes(n.href)
                : n.orgs.includes(s?.orgId || ''))).map((n) => (
                <Link key={n.href} className="v2-item" href={n.href} title={railed ? n.label : undefined}
                  aria-current={isActive(n.href) ? 'page' : undefined}>
                  <iconify-icon icon={n.icon}></iconify-icon><span>{n.label}</span>
                </Link>
              ))}
            </div>
          )}
        </nav>

        <div className="v2-foot" ref={acctRef}>
          {/* The four places we live, as a row of marks when the sidebar has the width for it; on
              the icon rail the same four move into the account menu instead. */}
          {!railed && (
            <div className="v2-socials" aria-label="Community links">
              {SOCIALS.map((x) => (
                <a key={x.label} className="v2-social" href={x.href} target="_blank" rel="noreferrer" title={x.label} aria-label={x.label}>
                  <iconify-icon icon={x.icon}></iconify-icon>
                </a>
              ))}
            </div>
          )}
          <button className="v2-account" type="button" aria-expanded={acctMenu}
            onClick={() => setAcctMenu((v) => !v)} title={railed ? acctLabel : undefined}>
            <span className="v2-avatar">
              {avatarUrl
                /* eslint-disable-next-line @next/next/no-img-element -- external OAuth photo, not a local asset */
                ? <img className="ph-no-capture" src={avatarUrl} alt="" referrerPolicy="no-referrer" />
                : initials}
            </span>
            {/* ph-no-capture: the email identifies the person. */}
            <span className="v2-email ph-no-capture">{acctLabel}</span>
          </button>
          {acctMenu && (
            <div className="account-menu" style={{ position: 'absolute', bottom: '100%', left: 12, right: 12, top: 'auto', marginBottom: 6 }}>
              {SELF_HOSTED ? (
                <div className="account-meta ph-no-capture"><strong>Signed in</strong><span>{selfHostUser || 'this instance'}</span></div>
              ) : (
                <div className="account-meta ph-no-capture"><strong>{s?.member?.name || 'Account'}</strong><span>{s?.member?.email || ''}</span></div>
              )}
              {SELF_HOSTED ? (
                <button className="menu-item" type="button" onClick={() => { setAcctMenu(false); router.push('/profile'); }}><iconify-icon icon="tabler:user-cog"></iconify-icon>Profile</button>
              ) : (<>
                <button className="menu-item" type="button" onClick={() => { setAcctMenu(false); router.push('/billing'); }}><iconify-icon icon="tabler:credit-card"></iconify-icon>Billing &amp; plan</button>
                <button className="menu-item" type="button" onClick={() => { setAcctMenu(false); router.push('/account'); }}><iconify-icon icon="tabler:settings"></iconify-icon>Account settings</button>
              </>)}
              <a className="menu-item" href="https://harnessrouter.ai/docs" target="_blank" rel="noreferrer"><iconify-icon icon="tabler:book-2"></iconify-icon>Docs</a>
              {railed && SOCIALS.map((x) => (
                <a key={x.label} className="menu-item" href={x.href} target="_blank" rel="noreferrer"><iconify-icon icon={x.icon}></iconify-icon>{x.label}</a>
              ))}
              {SELF_HOSTED ? (
                <button className="menu-item" type="button" onClick={async () => {
                  setAcctMenu(false);
                  await fetch('/api/selfhost/logout', { method: 'POST' }).catch(() => undefined);
                  // Full navigation: the middleware must re-evaluate without the cookie.
                  window.location.assign('/login');
                }}><iconify-icon icon="tabler:logout"></iconify-icon>Sign out</button>
              ) : (
                <button className="menu-item" type="button" onClick={() => { logout(); router.replace('/login'); }}><iconify-icon icon="tabler:logout"></iconify-icon>Sign out</button>
              )}
            </div>
          )}
        </div>
      </aside>

      {/* Cmd+K search: the v2 chrome has no header, so search lives in a palette overlay. All
          search state/logic is unchanged - only where the input renders moved. */}
      {searchOpen && (
        <div className="v2-search-overlay" onMouseDown={() => setSearchOpen(false)}>
          <div className="v2-search-box" ref={searchRef} onMouseDown={(e) => e.stopPropagation()}>
            <div className="global-search">
              <iconify-icon icon="tabler:search" aria-hidden="true"></iconify-icon>
              <input type="search" placeholder="Search workspaces, harnesses, tasks"
                aria-label="Search workspaces, harnesses, and tasks" role="combobox"
                aria-expanded={searchOpen} aria-controls="global-search-panel" autoComplete="off"
                ref={searchInputRef} value={query} autoFocus
                onChange={(e) => { setQuery(e.target.value); void ensureSearchData(); }}
                onKeyDown={onSearchKey} />
              <span className="search-key">esc</span>
            </div>
            {q ? (
              <div className="search-panel" id="global-search-panel" role="listbox" aria-label="Search results">
                {flat.length === 0 ? (
                  <div className="search-empty">{searchLoading ? 'Searching…' : `No matches for “${query.trim()}”`}</div>
                ) : (
                  <>
                    {renderGroup('Workspaces', 'tabler:building', groups!.ws, 0)}
                    {renderGroup('Harnesses', 'tabler:assembly', groups!.hs, groups!.ws.length)}
                    {renderGroup('Tasks', 'tabler:list-details', groups!.ts, groups!.ws.length + groups!.hs.length)}
                  </>
                )}
              </div>
            ) : null}
          </div>
        </div>
      )}

      <main className="v2-main" ref={mainRef}>{children}</main>

      {wsCreate && (
        <div className="modal-backdrop">
          <section className="modal" role="dialog" aria-modal="true" aria-labelledby="newWsTitle" onClick={(e) => e.stopPropagation()}>
            <div className="modal-header">
              <div><h2 id="newWsTitle">Create Workspace</h2><p>Create a business or environment boundary for its Harnesses, Tasks, API Keys, and Revenue.</p></div>
              <button className="icon-button modal-close" type="button" aria-label="Close dialog" onClick={() => setWsCreate(false)}><iconify-icon icon="tabler:x"></iconify-icon></button>
            </div>
            <div className="modal-body">
              <form onSubmit={submitCreate}>
                <div className="field-stack">
                  <div className="field"><label htmlFor="newWsName">Name</label>
                    <input id="newWsName" value={wsName} placeholder="Customer Support" autoFocus
                      onChange={(e) => setWsName(e.target.value)} />
                    <span className="field-help">Use a product, customer, or environment name your team will recognize.</span></div>
                  <div className="field"><label htmlFor="newWsDesc">Description <span className="optional-label">Optional</span></label>
                    <textarea id="newWsDesc" value={wsDesc} placeholder="Customer-facing support workflows."
                      onChange={(e) => setWsDesc(e.target.value)} /></div>
                  {wsErr && <div className="notice"><iconify-icon icon="tabler:alert-triangle"></iconify-icon><div><strong>Could not create</strong>{wsErr}</div></div>}
                </div>
                <div className="creation-next"><iconify-icon icon="tabler:arrow-right"></iconify-icon><span>After creation, Quickstart opens so you can connect a coding agent and create the first Workspace API Key.</span></div>
                <div className="modal-actions">
                  <button className="button" type="button" onClick={() => setWsCreate(false)} disabled={wsBusy}>Cancel</button>
                  <button className="button primary" type="submit" disabled={wsBusy || !wsName.trim()}>{wsBusy ? 'Creating…' : 'Create Workspace'}</button>
                </div>
              </form>
            </div>
          </section>
        </div>
      )}
    </>
  );
}
