import { test, expect } from '@playwright/test';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('localhost login uses real HttpOnly session cookies, rejects bad passwords and recovers expiry', async ({ page, context, baseURL }) => {
  await page.goto(baseURL!.replace('127.0.0.1', 'localhost'));
  const login = page.getByRole('dialog', { name: '登录 Hexa', exact: true });
  await login.getByLabel('密码', { exact: true }).fill('wrong-password');
  await login.getByRole('button', { name: '登录', exact: true }).click();
  await expect(login.getByRole('alert')).toContainText('用户名或密码错误');
  await login.getByLabel('密码', { exact: true }).fill('integration-password');
  await login.getByRole('button', { name: '登录', exact: true }).click();
  await expect(login).toBeHidden();
  const cookie = (await context.cookies()).find(row => row.name === 'hexa_session');
  expect(cookie?.httpOnly).toBe(true);
  expect(cookie?.domain).toBe('localhost');
  await page.getByRole('textbox', { name: '消息输入' }).fill('真实会话草稿');
  await page.reload();
  await expect(page.getByRole('button', { name: '用户菜单：admin', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await context.clearCookies();
  await page.reload();
  await expect(login).toBeVisible();
  await login.getByLabel('密码', { exact: true }).fill('integration-password');
  await login.getByRole('button', { name: '登录', exact: true }).click();
  await expect(login).toBeHidden();
  await expect(page.getByRole('textbox', { name: '消息输入' })).toHaveValue('真实会话草稿');
  await page.getByRole('button', { name: '用户菜单：admin', exact: true }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await expect(login).toBeVisible();
  await page.reload();
  await expect(login).toBeVisible();
});

test('real browser + Vite + FastAPI + HTTP Gateway fixture: cookie, files, SSE, continuation and refresh', async ({ page, context }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('密码', { exact: true }).fill('integration-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '登录 Hexa' })).toBeHidden();
  const cookies = await context.cookies();
  expect(cookies.find(cookie => cookie.name === 'hexa_session')?.httpOnly).toBe(true);
  expect(await page.evaluate(() => document.cookie)).not.toContain('hexa_session');
  await page.getByRole('combobox', { name: '会话 Agent' }).selectOption('e2e-agent');
  await page.locator('input[type="file"]').setInputFiles({ name: 'input.txt', mimeType: 'text/plain', buffer: Buffer.from('attachment content') });
  await expect(page.getByText('文件 · input.txt', { exact: false })).toBeVisible();
  await page.getByRole('textbox', { name: '消息输入' }).fill('首轮');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('实时', { timeout: 10000 });
  await expect(page.getByText('实时回答：首轮', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '发送消息', exact: true })).toBeDisabled();
  await page.getByRole('textbox', { name: '消息输入' }).fill('追问');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await expect(page.getByText('实时回答：追问', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('实时回答：追问', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '产物', exact: true }).click();
  await expect(page.getByText('report.txt', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: '安全预览', exact: true }).first().click();
  await expect(page.getByText('generated report', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载', exact: true }).first().click();
  expect((await downloadEvent).suggestedFilename()).toBe('report.txt');
  await page.screenshot({ path: join(tmpdir(), 'hexa-app-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await page.screenshot({ path: join(tmpdir(), 'hexa-app-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '展开上下文' }).click();
  await expect(page.getByRole('complementary', { name: '会话检查器' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: join(tmpdir(), 'hexa-app-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('Agent management traverses Cookie authentication, FastAPI and the HTTP Gateway adapter', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('密码', { exact: true }).fill('integration-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '登录 Hexa' })).toBeHidden();
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await page.getByRole('button', { name: '创建 Agent', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '创建 Agent', exact: true });
  await dialog.getByLabel('Agent 名称', { exact: true }).fill('HTTP 边界助手');
  await dialog.getByLabel('后端', { exact: true }).fill('codex');
  await dialog.getByLabel('默认模型', { exact: true }).fill('e2e-model');
  await dialog.getByRole('button', { name: '创建', exact: true }).click();
  await expect(dialog).toBeHidden();
  const card = page.locator('.agent-grid article').filter({ has: page.getByRole('heading', { name: 'HTTP 边界助手' }) });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: '开始对话', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '会话 Agent' })).toHaveValue('e2e-created');
  await expect(page.getByRole('combobox', { name: '会话模型' })).toHaveValue('e2e-model');
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await page.getByRole('button', { name: '删除 HTTP 边界助手', exact: true }).click();
  await page.getByRole('dialog', { name: '删除 Agent', exact: true }).getByRole('button', { name: '删除', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'HTTP 边界助手' })).toBeHidden();
  await page.reload();
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await expect(page.getByRole('heading', { name: '集成测试 Agent' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'HTTP 边界助手' })).toBeHidden();
});
