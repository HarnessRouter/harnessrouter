import { test, expect } from '@playwright/test';

test('Agent templates cross browser, authenticated API, persistent database and HTTP Gateway', async ({ page }) => {
  const customName = `持久化客户模板-${test.info().project.name}`;
  const errors: string[] = [], urls: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => urls.push(request.url()));
  await page.goto('/');
  await page.getByLabel('密码', { exact: true }).fill('integration-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '登录 Hexa' })).toBeHidden();
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await page.getByRole('tab', { name: '模板库', exact: true }).click();
  const catalog = page.getByRole('region', { name: 'Agent 模板' });
  const gateway = catalog.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Codex HTTP 模板', exact: true }) });
  await gateway.getByRole('button', { name: '另存为自定义', exact: true }).click();
  const template = page.getByRole('dialog', { name: '新建自定义模板', exact: true });
  await template.getByRole('textbox', { name: '模板名称', exact: true }).fill(customName);
  await template.getByLabel('说明', { exact: true }).fill('真实 Cookie 与数据库链路');
  await template.getByRole('button', { name: '保存模板', exact: true }).click();
  await expect(template).toBeHidden();
  await page.reload();
  await page.getByRole('button', { name: '智能体', exact: true }).click();
  await page.getByRole('tab', { name: '模板库', exact: true }).click();
  const custom = catalog.getByRole('article').filter({ has: page.getByRole('heading', { name: customName, exact: true }) }).first();
  await expect(custom).toContainText('真实 Cookie 与数据库链路');
  await custom.getByRole('button', { name: '使用模板', exact: true }).click();
  const agent = page.getByRole('dialog', { name: '创建 Agent', exact: true });
  await expect(agent.getByRole('textbox', { name: '系统提示词', exact: true })).toHaveValue('HTTP 模板提示词');
  await agent.getByRole('textbox', { name: 'Agent 名称', exact: true }).fill('模板创建的 HTTP Agent');
  await agent.getByRole('button', { name: '创建', exact: true }).click();
  await expect(agent).toBeHidden();
  await expect(page.getByRole('heading', { name: '模板创建的 HTTP Agent', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '删除 模板创建的 HTTP Agent', exact: true }).click();
  await page.getByRole('dialog', { name: '删除 Agent', exact: true }).getByRole('button', { name: '删除', exact: true }).click();
  await page.getByRole('tab', { name: '模板库', exact: true }).click();
  await custom.getByRole('button', { name: '删除模板', exact: true }).click();
  await page.getByRole('dialog', { name: '删除自定义模板', exact: true }).getByRole('button', { name: '删除', exact: true }).click();
  await expect(custom).toBeHidden();
  expect(errors).toEqual([]);
  expect(urls.some(url => url.includes('/v1/') || url.includes('/api/harness'))).toBe(false);
});
