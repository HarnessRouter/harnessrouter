import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('task workflow and runs persist through the real session API, SQL database and HTTP Gateway', async ({ page }) => {
  const requests: string[] = [], errors: string[] = [];
  const gatewayRequests: string[] = [];
  page.on('request', request => {
    const path = new URL(request.url()).pathname;
    if (request.method() !== 'GET') requests.push(path);
    if (path.startsWith('/v1/')) gatewayRequests.push(path);
  });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('密码', { exact: true }).fill('integration-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '登录 Hexa' })).toBeHidden();
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '任务', exact: true }).click();
  await page.getByRole('region', { name: '任务列表区域' }).getByRole('button', { name: '新建任务', exact: true }).click();
  const form = page.getByRole('dialog', { name: '新建任务', exact: true });
  const title = `真实任务-${test.info().project.name}`;
  await form.getByLabel('任务名称', { exact: true }).fill(title);
  await form.getByLabel('任务输入', { exact: true }).fill('分析任务接入');
  await form.getByRole('button', { name: '创建任务', exact: true }).click();
  const detail = page.getByRole('complementary', { name: '任务详情', exact: true });
  await expect(detail).toContainText('无来源模板');
  await detail.getByRole('button', { name: '编辑流程', exact: true }).click();
  await page.getByRole('button', { name: '添加节点', exact: true }).click();
  await page.getByRole('group', { name: '节点 新节点 1', exact: true }).click();
  await page.getByLabel('节点名称', { exact: true }).fill('最终分析');
  await page.getByLabel('节点 Agent', { exact: true }).selectOption('e2e-agent');
  await expect(page.getByLabel('节点模型', { exact: true })).toHaveValue('e2e-model');
  await page.getByLabel('节点提示词', { exact: true }).fill('分析后输出报告');
  await page.getByLabel('最终报告', { exact: true }).check();
  await page.getByRole('button', { name: '保存任务流程', exact: true }).click();
  await expect(detail).toContainText('当前工作流 · v2');
  await detail.getByRole('button', { name: '运行', exact: true }).click();
  await page.getByRole('dialog', { name: '确认运行任务', exact: true }).getByRole('button', { name: '确认运行', exact: true }).click();
  const runDetail = page.getByRole('complementary', { name: '运行详情', exact: true });
  await expect(runDetail).toContainText('已完成', { timeout: 20000 });
  await expect(runDetail).toContainText('Workflow v2');
  await runDetail.getByRole('button', { name: '打开流程图', exact: true }).click();
  await page.getByRole('tab', { name: '调试', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '运行属性', exact: true })).toContainText('实时回答', { timeout: 10000 });
  const artifacts = page.getByRole('complementary', { name: '运行属性', exact: true }).getByRole('region', { name: '任务产物' });
  await expect(artifacts).toContainText('report.txt');
  const downloadResponse = page.waitForResponse(response => /\/api\/hexa\/artifacts\/\d+\/content$/.test(new URL(response.url()).pathname));
  const downloadEvent = page.waitForEvent('download');
  await artifacts.locator('button').click();
  const [response, download] = await Promise.all([downloadResponse, downloadEvent]);
  expect(response.status()).toBe(200);
  expect(response.headers()['content-type']).toBe('application/octet-stream');
  expect(response.headers()['content-disposition']).toMatch(/^attachment;/);
  expect(response.headers()['x-content-type-options']).toBe('nosniff');
  expect(download.suggestedFilename()).toBe('report.txt');
  expect(await readFile((await download.path())!, 'utf8')).toBe('generated report');
  const writes = requests.length;
  await page.getByRole('button', { name: '重放', exact: true }).click();
  await page.getByRole('tab', { name: '运行', exact: true }).click();
  await page.getByLabel('重放进度', { exact: true }).fill('0');
  expect(requests.length).toBe(writes);
  await page.getByRole('button', { name: '返回运行详情', exact: true }).click();
  await runDetail.getByRole('button', { name: '返回所属任务', exact: true }).click();
  await page.reload();
  await page.getByRole('row', { name: new RegExp(title) }).click();
  await expect(detail).toContainText('当前工作流 · v2');
  await detail.getByRole('button', { name: '保存为模板', exact: true }).click();
  const save = page.getByRole('dialog', { name: '保存为模板', exact: true });
  await expect(save.getByLabel('保存模板目标')).toHaveValue('');
  await save.getByRole('button', { name: '保存模板', exact: true }).click();
  await expect(save).toBeHidden();
  await page.getByRole('navigation', { name: '任务菜单' }).getByRole('button', { name: /模板管理/ }).click();
  const templateDetail = page.getByRole('complementary', { name: '模板详情', exact: true });
  await expect(templateDetail).toContainText(title);
  await templateDetail.getByRole('button', { name: '使用此模板', exact: true }).click();
  await form.getByLabel('任务名称', { exact: true }).fill(`${title}-副本`);
  await form.getByRole('button', { name: '创建任务', exact: true }).click();
  await expect(detail).toContainText('来源模板：#');
  await expect(detail).toContainText('尚未运行');
  expect(errors).toEqual([]);
  expect(requests.some(url => url.includes('/v1/'))).toBe(false);
  expect(gatewayRequests).toEqual([]);
});
