import { test, expect } from '@playwright/test';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test.beforeEach(async ({ page }) => {
  await page.route('**/api/hexa/**', route => route.fulfill({ json: { authenticated: true, username: 'admin', agents: [], conversations: [], workspaces: [], selected_id: null } }));
  await page.goto('/');
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '任务', exact: true }).click();
  await page.locator('.sidebar').getByRole('button', { name: /运行记录 12/ }).click();
});

test('run history shows a dependency graph, read-only playback and synchronized properties', async ({ page }) => {
  const writes: string[] = [];
  page.on('request', req => { if (req.method() !== 'GET') writes.push(req.url()); });
  await page.setViewportSize({ width: 1440, height: 900 });
  const graph = page.getByRole('main', { name: '运行流程图' });
  const properties = page.getByRole('complementary', { name: '运行属性' });
  await expect(graph.getByRole('region', { name: '运行状态画布' })).toBeVisible();
  await expect(properties.getByRole('heading', { name: '节点', exact: true })).toBeVisible();
  const canvas = page.getByRole('region', { name: '运行状态画布' });
  await expect(canvas).toBeVisible();
  await expect(graph).toHaveClass(/task-run-flow-infinite/);
  await expect(canvas).toHaveClass(/run-graph-canvas-infinite/);
  await expect(properties.getByRole('button', { name: '收起运行属性', exact: true })).toBeVisible();
  const toolbar = canvas.getByText('无限画布 · 状态流程图').locator('..');
  await expect(toolbar.getByRole('button', { name: '重放', exact: true })).toBeVisible();
  await expect(toolbar.getByRole('button', { name: '切换纵向布局', exact: true })).toBeVisible();
  await expect(toolbar).toContainText('横向布局');
  await toolbar.getByRole('button', { name: '切换纵向布局', exact: true }).click();
  await expect(toolbar).toContainText('纵向布局');
  await toolbar.getByRole('button', { name: '切换横向布局', exact: true }).click();
  await expect(toolbar).toContainText('横向布局');
  await expect(toolbar.getByRole('button', { name: '重放', exact: true })).toBeVisible();
  await toolbar.getByRole('button', { name: '重放', exact: true }).click();
  await expect(toolbar.getByRole('button', { name: '暂停重放', exact: true })).toBeVisible();
  await toolbar.getByRole('button', { name: '暂停重放', exact: true }).click();
  const zoomBeforeWheel = await toolbar.getByText(/\d+%/).innerText();
  const canvasBox = (await canvas.boundingBox())!;
  await page.mouse.move(canvasBox.x + canvasBox.width / 2, canvasBox.y + canvasBox.height / 2);
  await page.mouse.wheel(0, -160);
  await expect(toolbar.getByText(/\d+%/)).not.toHaveText(zoomBeforeWheel);
  await expect(canvas.locator('.react-flow__edge')).toHaveCount(8);
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await properties.getByRole('button', { name: '返回最新', exact: true }).click();
  await graph.getByRole('button', { name: '告警分析 节点', exact: true }).click();
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(properties).toContainText('告警分析');
  await expect(properties).toContainText('已完成');
  await expect(properties.getByRole('tablist', { name: '运行属性标签' })).toBeVisible();
  await expect(properties.getByRole('tab')).toHaveCount(4);
  for (const name of ['运行', '事件', '调试']) {
    await properties.getByRole('tab', { name, exact: true }).click();
    await expect(properties.getByRole('tab', { name, exact: true })).toHaveAttribute('aria-selected', 'true');
  }
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  const box = (await canvas.boundingBox())!, propBox = (await properties.boundingBox())!;
  expect(box.width).toBeGreaterThan(propBox.width);
  expect(box.height).toBeGreaterThan(450);
  expect(box.x + box.width).toBeLessThanOrEqual(propBox.x + 1);
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await properties.getByRole('button', { name: '重放', exact: true }).click();
  await expect(properties.getByRole('button', { name: '暂停重放', exact: true })).toBeVisible();
  await properties.getByRole('button', { name: '暂停重放', exact: true }).click();
  await properties.getByRole('slider', { name: '重放进度' }).fill('0');
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(properties).toContainText('待执行');
  await expect(properties).toContainText('尚无节点事件');
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await properties.getByRole('button', { name: '下一步', exact: true }).click();
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(properties).toContainText('执行中');
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await properties.getByRole('button', { name: '上一步', exact: true }).click();
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(properties).toContainText('待执行');
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await properties.getByRole('button', { name: '返回最新', exact: true }).click();
  await properties.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(properties).toContainText('已完成');
  await page.screenshot({ path: join(tmpdir(), 'hexa-run-history-desktop.png') });
  const list = page.getByRole('button', { name: '收起运行记录', exact: true });
  await list.click();
  await expect(page.getByRole('button', { name: '产品方案评估 已完成', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '展开运行记录', exact: true }).click();
  await page.getByRole('button', { name: '产品方案评估 已完成', exact: true }).click();
  await expect(graph.getByRole('button', { name: '暂停重放', exact: true })).toHaveCount(0);
  await expect(properties).toContainText('产品分析');
  await properties.getByRole('tab', { name: '运行', exact: true }).click();
  await expect(properties).toContainText('产品方案评估');
  await expect(canvas.locator('.react-flow__edge')).toHaveCount(3);
  await properties.getByRole('button', { name: '收起运行属性', exact: true }).click();
  await expect(page.getByRole('button', { name: '展开运行属性', exact: true })).toBeVisible();
  await expect(page.getByRole('complementary', { name: '运行属性（已收起）' })).toBeVisible();
  await page.getByRole('button', { name: '展开运行属性', exact: true }).click();
  await expect(properties.getByRole('tablist', { name: '运行属性标签' })).toBeVisible();
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await page.screenshot({ path: join(tmpdir(), 'hexa-run-history-dark.png') });
  expect(writes).toEqual([]);
});

test('mobile run selection, replay and properties drawer stay within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const graph = page.getByRole('main', { name: '运行流程图' });
  await expect(page.getByRole('complementary', { name: '运行属性' })).toHaveCount(0);
  await graph.getByRole('button', { name: '告警分析 节点', exact: true }).click();
  const drawer = page.getByRole('dialog', { name: '运行属性' });
  await expect(drawer).toBeVisible();
  await drawer.getByRole('tab', { name: '运行', exact: true }).click();
  await drawer.getByRole('combobox', { name: '选择运行记录' }).selectOption('run-17');
  await page.keyboard.press('Escape');
  await graph.getByRole('button', { name: '产品分析 节点', exact: true }).click();
  await expect(drawer).toBeVisible();
  await drawer.getByRole('tab', { name: '节点', exact: true }).click();
  await expect(drawer).toContainText('产品分析');
  await expect(drawer.getByRole('tab')).toHaveCount(4);
  await drawer.getByRole('tab', { name: '事件', exact: true }).click();
  await expect(drawer.getByRole('tab', { name: '事件', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.screenshot({ path: join(tmpdir(), 'hexa-run-history-mobile.png') });
  await page.keyboard.press('Escape');
  await expect(drawer).toBeHidden();
  await graph.getByRole('button', { name: '产品分析 节点', exact: true }).click();
  await drawer.getByRole('tab', { name: '运行', exact: true }).click();
  await drawer.getByRole('button', { name: '重放', exact: true }).click();
  await drawer.getByRole('button', { name: '暂停重放', exact: true }).click();
  await drawer.getByRole('slider', { name: '重放进度' }).fill('0');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: join(tmpdir(), 'hexa-run-history-mobile-canvas.png') });
});
